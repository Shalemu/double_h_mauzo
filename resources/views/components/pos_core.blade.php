// Builds a compact page list like [1, '...', 24, 25, 26, 27, 28, '...', 50]
// instead of listing every page number.
function getPageWindow(current, total, delta = 2) {
    const pages = [];
    for (let i = 1; i <= total; i++) {
        if (i === 1 || i === total || (i >= current - delta && i <= current + delta)) {
            pages.push(i);
        }
    }

    const withDots = [];
    let last = null;
    pages.forEach(p => {
        if (last !== null && p - last > 1) {
            withDots.push('...');
        }
        withDots.push(p);
        last = p;
    });

    return withDots;
}

$(document).ready(function() {
    // --- PRODUCT FILTER & PAGINATION ---
    const itemsPerPage = 10;
    let currentPage = 1;

    // Show retail or wholesale price on every product card, based on the selected tab.
    // The product itself never changes - only which price is displayed/used for the cart.
    function applySaleTypePricing() {
        const selectedType = $('input[name="sale-type"]:checked').val() || 'retail';

        $('.product-card').each(function() {
            const card = $(this);
            const price = selectedType === 'wholesale'
                ? parseFloat(card.data('wholesale-price')) || 0
                : parseFloat(card.data('retail-price')) || 0;

            card.attr('data-price', price);
            card.find('.product-price-label').text('Tsh ' + price.toLocaleString());
        });
    }

    function updateProducts() {
        const query = String($('#product-search').val() || '').trim().toLowerCase();

        // Filter products
        // Read attributes as strings: jQuery's .data() turns numeric
        // barcodes/names into numbers, and .includes() then throws.
        const filtered = $('.product-card').filter(function() {
            if (!query) return true;
            const name = String($(this).attr('data-name') || '').toLowerCase();
            const barcode = String($(this).attr('data-barcode') || '').toLowerCase();
            const brand = String($(this).attr('data-brand') || '');
            const id = String($(this).attr('data-id') || '');

            return name.includes(query) || barcode.includes(query) || brand.includes(query)
                || (brand + ' ' + name).includes(query) || id === query;
        });

        $('.product-card').hide();

        // Pagination
        const totalItems = filtered.length;
        const totalPages = Math.ceil(totalItems / itemsPerPage);
        if (currentPage > totalPages) currentPage = 1;
        if (currentPage < 1) currentPage = 1;

        const start = (currentPage - 1) * itemsPerPage;
        const end = start + itemsPerPage;
        filtered.slice(start, end).show();

        // Pagination UI — show a small window of pages around the current
        // one (plus first/last) instead of every page number at once.
        const pagination = $('#product-pagination');
        pagination.empty();

        pagination.append(`
            <li class="page-item ${currentPage === 1 ? 'disabled' : ''}">
                <a class="page-link" href="#" data-page="${currentPage - 1}">Prev</a>
            </li>
        `);

        getPageWindow(currentPage, totalPages, 2).forEach(p => {
            if (p === '...') {
                pagination.append(`
                    <li class="page-item disabled"><span class="page-link">&hellip;</span></li>
                `);
            } else {
                pagination.append(`
                    <li class="page-item ${p === currentPage ? 'active' : ''}">
                        <a class="page-link" href="#" data-page="${p}">${p}</a>
                    </li>
                `);
            }
        });

        pagination.append(`
            <li class="page-item ${currentPage === totalPages ? 'disabled' : ''}">
                <a class="page-link" href="#" data-page="${currentPage + 1}">Next</a>
            </li>
        `);
    }

    // Initial display
    applySaleTypePricing();
    updateProducts();

    // Search/filter
    $('#product-search, #sale-type-filter').on('input change', function() {
        currentPage = 1;
        updateProducts();
    });

    // Only part of a big shop's products is on the page, so also ask the
    // server (in the background — a reload would empty the cart) and add any
    // matching cards that aren't loaded yet.
    const searchInput = $('#product-search');
    const productList = document.getElementById('product-list');
    const searchUrl = productList ? productList.dataset.searchUrl : '';
    const searchStatus = $('#product-search-status');
    const needsServerSearch = searchUrl && searchInput.attr('data-truncated') === '1';
    const searchedTerms = new Set();
    let searchTimer = null;
    let searchRequest = null;

    function serverSearch(term) {
        term = String(term || '').trim();
        if (!needsServerSearch || term.length < 2 || searchedTerms.has(term.toLowerCase())) return;

        if (searchRequest) searchRequest.abort();
        searchStatus.removeClass('d-none').text('Searching all products…');

        searchRequest = $.ajax({ url: searchUrl, data: { q: term }, dataType: 'html' })
            .done(function(html) {
                searchedTerms.add(term.toLowerCase());
                const wrapper = document.createElement('div');
                wrapper.innerHTML = html;
                const added = [];
                wrapper.querySelectorAll('.product-card').forEach(function(card) {
                    if (productList.querySelector('.product-card[data-id="' + card.dataset.id + '"]')) return;
                    productList.querySelector('.alert')?.remove();
                    productList.appendChild(card);
                    added.push(card);
                });
                if (added.length) {
                    document.dispatchEvent(new CustomEvent('pos:cards-added', { detail: added }));
                    applySaleTypePricing();
                    updateProducts();
                }
                searchStatus.addClass('d-none').text('');
            })
            .fail(function(xhr, status) {
                if (status === 'abort') return;
                searchStatus.removeClass('d-none').text('Could not search all products. Check your connection and try again.');
            })
            .always(function() { searchRequest = null; });
    }

    searchInput.on('input', function() {
        clearTimeout(searchTimer);
        const term = $(this).val();
        searchTimer = setTimeout(function() { serverSearch(term); }, 400);
    });

    searchInput.on('keydown', function(e) {
        if (e.key !== 'Enter') return;
        e.preventDefault();
        clearTimeout(searchTimer);
        serverSearch($(this).val());
    });

    // Switching between Retail / Wholesale updates the displayed price for every product
    $('input[name="sale-type"]').on('change', function() {
        applySaleTypePricing();
    });

    // Pagination click
    $(document).on('click', '#product-pagination .page-link', function(e) {
        e.preventDefault();
        const page = parseInt($(this).data('page'));
        if (!isNaN(page)) {
            currentPage = page;
            updateProducts();
        }
    });
});

