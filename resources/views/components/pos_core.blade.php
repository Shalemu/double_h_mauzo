                confirmButtonColor: '#198754',
                denyButtonColor: '#6c757d'
            });

            if (receiptChoice.isConfirmed) {
                printThermalReceipt(sale);
            }

            cart = {};
            resetSaleForm();
            updateCartDisplay();
        } catch (err) {
            Swal.fire({ icon: 'error', title: 'Checkout Error', text: 'Checkout failed: ' + err.message, confirmButtonColor: '#d33' });
